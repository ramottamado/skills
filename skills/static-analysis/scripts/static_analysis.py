# /// script
# requires-python = ">=3.13"
# dependencies = ["lizard>=1.17"]
# ///
"""Run PMD (Java) and Lizard (Python) against one shared set of thresholds.

Usage:
    uv run --script static_analysis.py config [ROOT]
    uv run --script static_analysis.py ruleset [ROOT] [-o pmd-ruleset.xml]
    uv run --script static_analysis.py python [ROOT] [PATH ...]
    uv run --script static_analysis.py java [ROOT] [PATH ...]
    uv run --script static_analysis.py all [ROOT]

Thresholds come from ROOT/static-analysis.toml, else [tool.static-analysis] in
ROOT/pyproject.toml, else the defaults below. Every `max_*` value is the
largest value that is still allowed: a function at the limit passes, one above
it fails. PMD reports at ">= level", so the script passes max + 1 to PMD.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path
from xml.sax.saxutils import quoteattr

DEFAULTS: dict[str, object] = {
    "max_ccn": 10,  # cyclomatic complexity per function (Java and Python)
    "max_nloc": 60,  # code lines per function (Java: NCSS, Python: NLOC)
    "max_params": 5,  # parameters per function (Java and Python)
    "max_cognitive": 15,  # cognitive complexity per function (Java and Python)
    "max_npath": 200,  # NPath complexity per method (Java only)
    "exclude": [],  # glob patterns, e.g. ["*/generated/*", "*/migrations/*"]
}
INT_KEYS = [k for k, v in DEFAULTS.items() if isinstance(v, int)]


def load_config(root: Path) -> tuple[dict[str, object], str]:
    cfg = dict(DEFAULTS)
    source = "defaults"
    standalone = root / "static-analysis.toml"
    pyproject = root / "pyproject.toml"
    data: dict[str, object] = {}
    if standalone.is_file():
        data = tomllib.loads(standalone.read_text())
        source = str(standalone)
    elif pyproject.is_file():
        found = tomllib.loads(pyproject.read_text()).get("tool", {}).get("static-analysis")
        if found:
            data, source = found, f"{pyproject} [tool.static-analysis]"
    unknown = set(data) - set(DEFAULTS)
    if unknown:
        sys.exit(f"error: unknown keys in {source}: {', '.join(sorted(unknown))}")
    cfg.update(data)
    for key in INT_KEYS:
        if not isinstance(cfg[key], int) or cfg[key] < 1:
            sys.exit(f"error: {key} must be a positive integer in {source}")
    if not isinstance(cfg["exclude"], list):
        sys.exit(f"error: exclude must be a list in {source}")
    return cfg, source


def ruleset_xml(cfg: dict[str, object]) -> str:
    def rule(name: str, **props: int) -> str:
        body = "".join(
            f'      <property name="{k}" value="{v}"/>\n' for k, v in props.items()
        )
        return (
            f'  <rule ref="category/java/design.xml/{name}">\n'
            f"    <properties>\n{body}    </properties>\n  </rule>\n"
        )

    # PMD reports at ">= level", the shared max_* values are inclusive limits.
    return (
        '<?xml version="1.0"?>\n'
        "<!-- Generated by static_analysis.py from the shared thresholds. -->\n"
        f"<ruleset name={quoteattr('static-analysis')}\n"
        '         xmlns="http://pmd.sourceforge.net/ruleset/2.0.0">\n'
        "  <description>Complexity thresholds shared with Lizard.</description>\n"
        + rule("CyclomaticComplexity", methodReportLevel=cfg["max_ccn"] + 1)
        + rule("CognitiveComplexity", reportLevel=cfg["max_cognitive"] + 1)
        + rule("NPathComplexity", reportLevel=cfg["max_npath"] + 1)
        + rule("NcssCount", methodReportLevel=cfg["max_nloc"] + 1)
        + rule("ExcessiveParameterList", minimum=cfg["max_params"] + 1)
        + "</ruleset>\n"
    )


def run_python(root: Path, cfg: dict[str, object], paths: list[str]) -> int:
    cmd = [
        sys.executable, "-m", "lizard", "-l", "python", "-w", "-Ecognitive",
        "-C", str(cfg["max_ccn"]),
        "-a", str(cfg["max_params"]),
        "-T", f"nloc={cfg['max_nloc']}",
        "-T", f"cognitive_complexity={cfg['max_cognitive']}",
    ]
    for pattern in cfg["exclude"]:
        cmd += ["-x", pattern]
    cmd += paths or ["."]
    print("+", " ".join(cmd), flush=True)
    return subprocess.run(cmd, cwd=root).returncode


def run_java(root: Path, cfg: dict[str, object], paths: list[str]) -> int:
    pmd = shutil.which("pmd")
    if not pmd:
        print("error: pmd is not on PATH; see references/pmd.md for install options", file=sys.stderr)
        return 2
    ruleset = root / ".pmd-ruleset.generated.xml"
    ruleset.write_text(ruleset_xml(cfg))
    cmd = [pmd, "check", "-R", str(ruleset), "-f", "text", "--no-cache"]
    for p in paths or ["."]:
        cmd += ["-d", p]
    for pattern in cfg["exclude"]:
        cmd += ["--exclude", pattern]
    print("+", " ".join(cmd), flush=True)
    try:
        return subprocess.run(cmd, cwd=root).returncode
    finally:
        ruleset.unlink(missing_ok=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["config", "ruleset", "python", "java", "all"])
    ap.add_argument("root", nargs="?", default=".")
    ap.add_argument("paths", nargs="*", help="files or folders to scan (python, java)")
    ap.add_argument("-o", "--output", default="pmd-ruleset.xml", help="ruleset path (ruleset)")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    cfg, source = load_config(root)

    if args.command == "config":
        print(f"# source: {source}")
        for k, v in cfg.items():
            print(f"{k} = {v!r}")
        return 0
    if args.command == "ruleset":
        out = Path(args.output)
        out = out if out.is_absolute() else root / out
        out.write_text(ruleset_xml(cfg))
        print(f"wrote {out}")
        return 0
    if args.command == "python":
        return run_python(root, cfg, args.paths)
    if args.command == "java":
        return run_java(root, cfg, args.paths)
    rc = run_python(root, cfg, []) if any(root.rglob("*.py")) else 0
    return max(rc, run_java(root, cfg, []) if any(root.rglob("*.java")) else 0)


if __name__ == "__main__":
    sys.exit(main())
